import { ApiError } from './httpClient'

// Универсальные тексты по HTTP/API-статусу — используются, когда у ошибки
// нет собственного осмысленного сообщения от сервера (см. ниже).
const STATUS_MESSAGES = {
  400: 'Некорректный запрос к серверу',
  401: 'Сессия истекла или доступ запрещён — попробуйте войти заново',
  403: 'Нет доступа к этим данным',
  404: 'Данные не найдены',
  408: 'Сервер долго не отвечает — попробуйте ещё раз',
  429: 'Слишком много запросов подряд — подождите немного и повторите',
  500: 'Ошибка на сервере, попробуйте позже',
  502: 'Сервер временно недоступен',
  503: 'Сервер временно недоступен',
  504: 'Сервер долго не отвечает — попробуйте ещё раз',
}

// Сырое сообщение вида "HTTP 500" — то, что httpClient.parseResponse кладёт
// в ApiError, когда сам HTTP-транспорт вернул ошибку (response.ok === false)
// и никакого текста от сервера нет. Показывать это пользователю как есть
// нельзя — заменяем на понятный текст по коду (см. STATUS_MESSAGES).
const RAW_HTTP_MESSAGE = /^HTTP \d+$/

// Превращает любую пойманную в catch ошибку в человекочитаемый русский
// текст для отображения пользователю (AsyncBoundary, форма логина,
// drill-through модалка и т.п.).
//
// options.fallback — текст по умолчанию, если ничего конкретнее не нашли.
// options.statusMessages — переопределение текста для конкретных кодов в
// контексте конкретного вызова (например, 401 на логине — это неверный
// телефон/пароль, а не "сессия истекла", как для остальных запросов).
//
// Пример:
// this.error = getErrorMessage(err, {
//   fallback: 'Не удалось войти. Проверьте телефон и пароль.',
//   statusMessages: { 401: 'Неверный телефон, пароль или ссылка доступа' },
// })
export function getErrorMessage(err, options = {}) {
  const { fallback = 'Что-то пошло не так, попробуйте ещё раз', statusMessages = {} } = options

  if (!err) return fallback

  // fetch не смог даже достучаться до сервера (нет интернета, CORS,
  // сервер недоступен) — бросает TypeError с техническим текстом вроде
  // "Failed to fetch", который для пользователя ничего не значит.
  if (err instanceof TypeError) {
    return 'Нет соединения с сервером. Проверьте интернет и попробуйте снова'
  }

  const status = err instanceof ApiError ? err.status : err?.status

  if (status && statusMessages[status]) return statusMessages[status]
  if (status && STATUS_MESSAGES[status]) return STATUS_MESSAGES[status]

  // Сообщение от самого API (result.Message) обычно уже осмысленное —
  // показываем как есть, кроме случая "голого" HTTP-статуса без текста.
  if (err.message && !RAW_HTTP_MESSAGE.test(err.message)) return err.message

  return fallback
}
